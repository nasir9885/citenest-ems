CREATE TABLE holidays (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id UUID NOT NULL,
    holiday_name_en VARCHAR(200) NOT NULL,
    holiday_name_ar VARCHAR(200),
    holiday_date DATE NOT NULL,
    holiday_type VARCHAR(20) NOT NULL DEFAULT 'PUBLIC',
    is_recurring BOOLEAN NOT NULL DEFAULT FALSE,
    description TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_holidays_tenant
        FOREIGN KEY (tenant_id)
        REFERENCES tenants (id)
        ON DELETE RESTRICT,

    CONSTRAINT uq_holidays_tenant_date_name
        UNIQUE (tenant_id, holiday_date, holiday_name_en),

    CONSTRAINT ck_holidays_type
        CHECK (holiday_type IN ('PUBLIC', 'COMPANY')),

    CONSTRAINT ck_holidays_status
        CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE INDEX ix_holidays_tenant_date
    ON holidays (tenant_id, holiday_date);

